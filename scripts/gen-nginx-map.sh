#!/usr/bin/env bash
# Generate the nginx stream SNI allow-map from the domain allowlist files.
# Output is an nginx `map` block: $ssl_preread_server_name -> $sni_ok (0/1).
#
#   usage: gen-nginx-map.sh <suffixes.conf> <exact.conf> <output.map>
set -euo pipefail

SUFFIXES="${1:?suffixes file}"
EXACT="${2:?exact file}"
OUT="${3:?output map file}"

# Basic hostname sanity: letters, digits, dot, hyphen only.
valid_host() { [[ "$1" =~ ^[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$ ]]; }

clean() { sed -e 's/#.*//' -e 's/[[:space:]]//g' "$1" | grep -v '^$' || true; }

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "# AUTO-GENERATED by gen-nginx-map.sh — do not edit by hand."
  echo "# Source: $(basename "$SUFFIXES") + $(basename "$EXACT")"
  echo "map \$ssl_preread_server_name \$sni_ok {"
  echo "    hostnames;"
  echo "    default 0;"
  # Suffix entries: leading dot => matches the name and all subdomains.
  while IFS= read -r d; do
    valid_host "$d" || { echo "invalid suffix domain: $d" >&2; exit 2; }
    printf '    .%s 1;\n' "$d"
  done < <(clean "$SUFFIXES")
  # Exact entries: no leading dot => exact match only.
  while IFS= read -r d; do
    valid_host "$d" || { echo "invalid exact domain: $d" >&2; exit 2; }
    printf '    %s 1;\n' "$d"
  done < <(clean "$EXACT")
  echo "}"
} > "$tmp"

# Atomic install.
install -m 0644 "$tmp" "$OUT"
echo "wrote $(grep -c ' 1;' "$OUT") allowed SNI patterns -> $OUT"
